// Approved 30 slots × A/B. Keys are zero based; immutable source, no generated questions.
export type AssessmentItem = {
  id: string;
  slot: number;
  lesson: number;
  level: "basic" | "medium" | "advanced";
  type: "mcq" | "tf" | "number";
  prompt: string;
  options?: string[];
  answer: number | boolean;
  explain: string;
  unit?: string;
  diagram?: string;
  conditions?: string;
};
const S = String.raw;
const items: AssessmentItem[] = [];
function pair(
  slot: number,
  type: AssessmentItem["type"],
  a: [string, string[] | null, number | boolean, string],
  b: typeof a,
  extra: Partial<AssessmentItem> = {},
) {
  [a, b].forEach((v, i) =>
    items.push({
      id: `u1-${slot}-${i ? "B" : "A"}`,
      slot,
      lesson: Math.ceil(slot / 6),
      level:
        slot % 6 === 0
          ? "advanced"
          : slot % 6 === 1 || slot % 6 === 2
            ? "basic"
            : "medium",
      type,
      prompt: v[0],
      ...(v[1] ? { options: v[1] } : {}),
      answer: v[2],
      explain: v[3],
      ...extra,
    }),
  );
}

/**
 * محتوى قسم «أراجع وأختبر نفسي — الوحدة الأولى» (ص 63–64 من الكتاب).
 *
 * المصدر الوحيد هو أسئلة الوحدة الأولى كما وردت في الصفحتين:
 * - السؤال الأول: خمس عبارات صح/خطأ مع التصحيح (كلها خاطئة كما طُبعت).
 * - السؤال الثاني: جدول أجسام على عدّة كواكب + ثلاثة أسئلة.
 * - السؤال الثالث: ثلاثة خطوط بيانية + وصف خصائص الحركة.
 * - السؤال الرابع: ثلاث مسائل (الخنفساء، الربيعات، الصندوق) بثلاث مهام لكل منها.
 *
 * لا يُضاف أي سؤال من خارج الصفحتين، ولا يُحذف معطى. الصياغة عُدّلت فقط
 * لإصلاح أخطاء مطبعية واضحة وإظهار الرموز والوحدات عبر KaTeX.
 */
import type { Rich } from "./types";
import { machineRich } from "./simple-machines-text";

const r = machineRich;
const S = String.raw;

export type Correction = { text: Rich; correct: boolean };

export type ReviewFigureName =
  | "graph-uniform"
  | "graph-accelerated"
  | "graph-rest"
  | "beetle"
  | "springs";

export type ReviewGroup = {
  id: string;
  title: string;
  intro?: Rich;
};

type Base = {
  id: string;
  source: string;
  label: string;
  explain: Rich;
  hint?: Rich;
  figure?: ReviewFigureName;
  group?: ReviewGroup;
};

/** صح أم خطأ، ثم اختيار التصحيح للعبارة الخاطئة. */
export type TrueFalseItem = Base & {
  kind: "tf";
  statement: Rich;
  isTrue: boolean;
  corrections: Correction[];
};

/** اختيار مفرد. */
export type SingleItem = Base & {
  kind: "single";
  prompt: Rich;
  options: Correction[];
};

/** اختيار جسمين معًا. */
export type PairItem = Base & {
  kind: "pair";
  prompt: Rich;
  options: Rich[];
  answer: [number, number];
};

/** إجابة عددية مع وحدة وخطوات حل. */
export type NumberItem = Base & {
  kind: "number";
  prompt: Rich;
  answer: number;
  alternates?: number[];
  unit: string;
  answerNote?: Rich;
  steps: Rich[];
};

export type TableColumn = {
  /** قيمة المسافة المطبوعة (null = خانة فارغة). */
  d: number | null;
  /** قيمة الزمن المطبوعة (null = خانة فارغة). */
  t: number | null;
  /** قيم المسافة المسموحة للاختيار في الأعمدة الفارغة. */
  dChoices?: number[];
};

/** إكمال جدول الكتاب (خمسة أعمدة كما طُبعت). */
export type TableItem = Base & {
  kind: "table";
  prompt: Rich;
  columns: TableColumn[];
  /** الزمن المتوقّع للعمود ذي المسافة المطبوعة 5 cm. */
  interpolation: { d: number; t: number };
  /** أزواج المسافة/الزمن المقبولة في الأعمدة الفارغة. */
  pairs: [number, number][];
  steps: Rich[];
};

/** تخطيط النقاط على شبكة ثم تحديد شكل الخط. */
export type PlotItem = Base & {
  kind: "plot";
  prompt: Rich;
  shapePrompt: Rich;
  requiredPoints: [number, number][];
  shapeOptions: Correction[];
  steps: Rich[];
};

/** قراءة ثلاث ربيعات مدرّجة. */
export type ScalesItem = Base & {
  kind: "scales";
  prompt: Rich;
  readings: { key: "a" | "b" | "c"; answer: number }[];
  steps: Rich[];
};

/** بناء مخطط القوى بالسحب والإفلات (أو اللمس). */
export type DiagramItem = Base & {
  kind: "diagram";
  prompt: Rich;
  tokens: { id: string; text: Rich; slot: "right" | "left" | "up" | "down" }[];
  steps: Rich[];
};

export type ReviewItem =
  | TrueFalseItem
  | SingleItem
  | PairItem
  | NumberItem
  | TableItem
  | PlotItem
  | ScalesItem
  | DiagramItem;

export type ReviewStation = {
  id: string;
  number: string;
  title: string;
  subtitle: string;
  source: string;
  intro: Rich;
  /** رسم/معطى مشترك يُعرض قبل بنود المحطة (مثل جدول السؤال الثاني). */
  figure?: string;
  items: ReviewItem[];
};


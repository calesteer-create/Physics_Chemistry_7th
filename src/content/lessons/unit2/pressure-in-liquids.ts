const SECTION_RE = /^(?:أولاً|ثانياً|ثالثاً|رابعاً|خامساً|سادساً|سابعاً|ثامناً|تاسعاً|عاشراً|حادي عشر):/u;

/** بيانات الدفتر للخط الأساس — كل سطر من المصدر المعتمد يبقى كما هو. */
function approvedNotebookItems(): NotebookItem[] {
  const blocks = pressureInLiquidsNotebookText.split(/\n\s*\n/u).filter(Boolean);
  const items: NotebookItem[] = [];
  const cover = (blocks.shift() ?? "").split("\n").filter(Boolean);
  items.push({ kind: "h1", text: cover[0] ?? "" });
  for (const line of cover.slice(1)) items.push({ kind: "write", rich: R(line) });
  for (const block of blocks) {
    const lines = block.split("\n").filter((line) => line.trim().length > 0);
    let cursor = 0;
    if (lines[0] && SECTION_RE.test(lines[0])) {
      items.push({ kind: "h2", text: lines[0] });
      cursor = 1;
    }
    for (const line of lines.slice(cursor)) items.push({ kind: "write", rich: R(line) });
  }
  return items;
}


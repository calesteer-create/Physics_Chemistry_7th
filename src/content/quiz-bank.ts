const QUIZZES: QuizFull[] = [orientationQuiz, motion1Quiz, force2Quiz, oneSupportQuiz];

export function getQuizFull(id: string): QuizFull | undefined {
  return QUIZZES.find((q) => q.id === id);
}

export function listQuizzesMeta(): { id: string; title: string; lessonSlug: string | null; count: number; durationMin: number; curricular: boolean }[] {
  return QUIZZES.map((q) => ({
    id: q.id,
    title: q.title,
    lessonSlug: q.lessonSlug,
    count: q.questions.length,
    durationMin: q.durationMin,
    curricular: q.curricular,
  }));
}

/** نسخة آمنة للمتصفح: بلا إجابات ولا شروح. */
export function sanitizeQuiz(quiz: QuizFull): QuizPublic {
  return {
    id: quiz.id,
    lessonSlug: quiz.lessonSlug,
    title: quiz.title,
    description: quiz.description,
    durationMin: quiz.durationMin,
    curricular: quiz.curricular,
    questions: quiz.questions,
  };
}
